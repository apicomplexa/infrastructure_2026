import sys, io
from pathlib import Path
ROOT = Path(r"D:\Projects\03_Science_and_Education\infrastructure_2026")
sys.path.insert(0, str(ROOT / "src"))
import pandas as pd, numpy as np
from arkhinfra import paths
out = io.StringIO()
def P(*a): print(*a, file=out)
m = pd.read_csv(paths.PROC/"match_2022_local.csv", sep=";", encoding="utf-8-sig", low_memory=False)
P("match_2022_local:", m.shape, list(m.columns))
P("\n=== tier x category_orig ===")
ct = pd.crosstab(m["category_orig"], m["tier"])
ct["linked"] = ct.get("exact",0)+ct.get("probable",0)
ct["n"] = ct.sum(axis=1)-ct["linked"]
ct["rate%"] = (100*ct["linked"]/ct["n"]).round(1)
P(ct.to_string())
P("\ntotals:", m["tier"].value_counts().to_dict())
P("\n=== category_2022 (recoded) on linked subset ===")
lk = m[m.tier.isin(["exact","probable"])]
P(lk["category_2022"].value_counts().to_string())
P("\n=== linked rows -> distinct target_index ===")
P("linked rows:", len(lk), "distinct target_index:", lk["target_index"].nunique())
P("target_index null in linked:", lk["target_index"].isna().sum())
P("\n=== name_sim on linked ===")
P("share >=0.99:", f"{100*(lk.name_sim>=0.99).mean():.1f}%", " >=0.95:", f"{100*(lk.name_sim>=0.95).mean():.1f}%")
P("\n=== gps_only name_sim median / addr_sim median ===")
gp = m[m.tier=="gps_only"]
P("n", len(gp), "name_sim med", round(gp.name_sim.median(),3), "addr_sim med", round(gp.addr_sim.median(),3))
P("\n=== okrug of linked rows ===")
P(lk["okrug_key"].value_counts().to_string())
P("\n=== benchmark okrug mix ===")
P(m["okrug_key"].value_counts().to_string())
P("\n=== per-okrug per-class linked ===")
P(pd.crosstab(lk["category_orig"], lk["okrug_key"]).to_string())
P("\n=== multi-class export rows ===")
g = lk.groupby("target_index")["category_orig"].nunique()
P("target rows with >1 category:", (g>1).sum())
g2 = lk.groupby("target_index").size()
P("collisions (target rows with >1 benchmark row):", (g2>1).sum(), " extra rows:", (g2-1).clip(lower=0).sum())
P("\n=== Пром. Объекты detail ===")
P(m[m.category_orig=="Пром. Объекты"][["type_orig","name_orig","tier","name_sim","distance_m"]].to_string())
P("\n=== null adress_orig in benchmark, by category ===")
P(m[m.adress_orig.isna()]["category_orig"].value_counts().to_string())
P("total null address:", m.adress_orig.isna().sum())
P("\n=== link rate by type_orig (n>=15) ===")
t = pd.crosstab(m["type_orig"], m["tier"].isin(["exact","probable"]))
t.columns=["no","yes"]; t["n"]=t.no+t.yes; t["rate"]=(100*t.yes/t.n).round(1)
P(t[t.n>=15].sort_values("rate").to_string())
